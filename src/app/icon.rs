//! The app icon and identity for every window we open.
//!
//! - Windows and X11 take the icon from the window itself (title bar,
//!   taskbar, Alt+Tab); the `.exe`'s own icon is embedded by `build.rs`.
//! - Wayland has no per-window icons: the compositor matches the window's
//!   app ID to `neoviz.desktop` and uses that file's icon, so the ID must
//!   match the desktop file's name (installed by `packaging/linux/install.sh`).

use winit::window::{Icon, WindowAttributes};

/// App ID / WM class; must match `packaging/linux/neoviz.desktop`.
#[cfg_attr(not(target_os = "linux"), allow(dead_code))]
const APP_ID: &str = "neoviz";

/// Generated by `packaging/make-icons.sh`.
const ICON_PNG: &[u8] = include_bytes!("../../assets/icon/neoviz-256.png");

/// Adds the icon and app ID to a new window's attributes.
pub fn apply(attrs: WindowAttributes) -> WindowAttributes {
    #[cfg(target_os = "linux")]
    let attrs = {
        // Wayland and X11 share this setting (app ID / WM_CLASS).
        use winit::platform::wayland::WindowAttributesExtWayland;
        attrs.with_name(APP_ID, APP_ID)
    };
    attrs.with_window_icon(window_icon())
}

fn window_icon() -> Option<Icon> {
    let decoded = decode_rgba(ICON_PNG)
        .and_then(|(rgba, w, h)| Icon::from_rgba(rgba, w, h).map_err(|e| anyhow::anyhow!("{e}")));
    match decoded {
        Ok(icon) => Some(icon),
        Err(e) => {
            log::warn!("can't use the window icon: {e:#}");
            None
        }
    }
}

/// Decodes a PNG to 8-bit RGBA pixels and its size.
fn decode_rgba(png_bytes: &[u8]) -> anyhow::Result<(Vec<u8>, u32, u32)> {
    let mut decoder = png::Decoder::new(std::io::Cursor::new(png_bytes));
    // Expand palettes, low bit depths and tRNS chunks to plain 8-bit channels.
    decoder.set_transformations(png::Transformations::normalize_to_color8());
    let mut reader = decoder.read_info()?;
    let mut buf = vec![0; reader.output_buffer_size().unwrap_or(0)];
    let info = reader.next_frame(&mut buf)?;
    buf.truncate(info.buffer_size());
    let rgba = match info.color_type {
        png::ColorType::Rgba => buf,
        png::ColorType::Rgb => buf
            .as_chunks::<3>()
            .0
            .iter()
            .flat_map(|&[r, g, b]| [r, g, b, u8::MAX])
            .collect(),
        png::ColorType::GrayscaleAlpha => buf
            .as_chunks::<2>()
            .0
            .iter()
            .flat_map(|&[g, a]| [g, g, g, a])
            .collect(),
        png::ColorType::Grayscale => buf.iter().flat_map(|&g| [g, g, g, u8::MAX]).collect(),
        other => anyhow::bail!("unexpected PNG colour type {other:?}"),
    };
    Ok((rgba, info.width, info.height))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_built_in_icon_decodes_to_square_rgba() {
        let (rgba, w, h) = decode_rgba(ICON_PNG).unwrap();
        assert_eq!((w, h), (256, 256));
        assert_eq!(rgba.len(), 256 * 256 * 4);
    }

    #[test]
    fn the_built_in_icon_is_accepted_by_winit() {
        assert!(window_icon().is_some());
    }
}
